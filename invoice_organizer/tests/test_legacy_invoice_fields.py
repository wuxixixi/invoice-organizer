def _parse_result(tokens: list[tuple[str, float, float]], name: str) -> ParseResult:
    """用固化 token 重建词级 + 行级字段，与 PdfTextAdapter 输出同构。"""
    words: list[dict[str, Any]] = [
        {"text": text, "x0": x0, "top": top, "x1": x0, "bottom": top}
        for text, x0, top in tokens
    ]
    fields = [
        RawTextField("", w["text"], 1, (w["x0"], w["top"], w["x1"], w["bottom"]))
        for w in words
    ]
    fields.extend(
        RawTextField("line", text, 1, bbox) for text, bbox in _group_lines(words)
    )
    return ParseResult(
        fields=fields, sourceHash="a" * 64, sourcePath=name,
        pageCount=1, adapterName="pdf_text",
    )


def _extract(tokens: list[tuple[str, float, float]], name: str) -> Any:
    """离线提取：llm_client=None，绝不访问大模型服务。"""
    config = ProfileConfig.default()
    config.amountSource = "totalExclTax"
    extractor = FieldExtractor(config=config, llm_client=None)
    return extractor.extract(_parse_result(tokens, name), config.amountSource)


def test_legacy_invoice_fields_are_corrected() -> None:
    """旧版增值税票四个错误字段应被纠正。"""
    inv = _extract(_LEGACY, "24933884.pdf")

    assert inv.get_field("issueDate").value == "2017-07-02"
    assert "餐饮" in inv.get_field("itemName").value
    assert inv.get_field("amountCent").value == "358.40"
    assert inv.amountCent == 35840

    buyer_tax = inv.get_field("buyerTaxId")
    assert buyer_tax.value == ""
    assert buyer_tax.confidence == Confidence.NEED_HUMAN
    assert inv.get_field("sellerTaxId").value == "91310101569564679R"


